"""SQLAlchemy models. The schema itself changes only through Alembic migrations."""

import uuid
from datetime import datetime
from typing import Any

from sqlalchemy import (
    JSON,
    BigInteger,
    CheckConstraint,
    DateTime,
    ForeignKey,
    Index,
    LargeBinary,
    String,
    Text,
    func,
    text,
)
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column


class Base(DeclarativeBase):
    # Every datetime column is `timestamptz`: stored in UTC, never ambiguous.
    type_annotation_map = {datetime: DateTime(timezone=True)}  # noqa: RUF012


class Notebook(Base):
    __tablename__ = "notebooks"

    id: Mapped[uuid.UUID] = mapped_column(primary_key=True, default=uuid.uuid4)
    title: Mapped[str] = mapped_column(String(200))
    created_at: Mapped[datetime] = mapped_column(server_default=func.now())
    updated_at: Mapped[datetime] = mapped_column(server_default=func.now(), onupdate=func.now())


class NotebookSnapshot(Base):
    """The whole Yjs document as one provisional, single-writer snapshot blob.

    One row per notebook. Phase 2 decides the real snapshot and compaction
    strategy; an update-log table can be added next to this one.
    """

    __tablename__ = "notebook_snapshots"

    notebook_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("notebooks.id", ondelete="CASCADE"), primary_key=True
    )
    state: Mapped[bytes] = mapped_column(LargeBinary)
    updated_at: Mapped[datetime] = mapped_column(server_default=func.now(), onupdate=func.now())


class CellRun(Base):
    """One execution of a cell's SQL and its outcome, shared by everyone.

    Results live here, not in the Yjs document; the document only stores the
    latest run's ID per cell.
    """

    __tablename__ = "cell_runs"
    __table_args__ = (
        Index("ix_cell_runs_notebook_cell_created", "notebook_id", "cell_id", "created_at"),
        CheckConstraint("status IN ('ok', 'error')", name="ck_cell_runs_status"),
        # An ok run has a result and no error; an error run the reverse.
        CheckConstraint(
            "(status = 'ok' AND result IS NOT NULL AND error IS NULL) OR "
            "(status = 'error' AND result IS NULL AND error IS NOT NULL)",
            name="ck_cell_runs_outcome",
        ),
    )

    id: Mapped[uuid.UUID] = mapped_column(primary_key=True, default=uuid.uuid4)
    notebook_id: Mapped[uuid.UUID] = mapped_column(ForeignKey("notebooks.id", ondelete="CASCADE"))
    # Cell IDs are generated by the client and live in the Yjs document.
    cell_id: Mapped[str] = mapped_column(String(64))
    sql: Mapped[str] = mapped_column(Text)
    status: Mapped[str] = mapped_column(String(16))  # "ok" or "error"
    # `json`, not `jsonb`: results are never queried inside, and jsonb rejects
    # the \u0000 escape, which a DuckDB string value can legitimately contain.
    # none_as_null: Python None must be SQL NULL (not JSON 'null'), or the
    # ck_cell_runs_outcome constraint would reject every run.
    result: Mapped[dict[str, Any] | None] = mapped_column(JSON(none_as_null=True))
    error: Mapped[dict[str, Any] | None] = mapped_column(JSON(none_as_null=True))
    created_at: Mapped[datetime] = mapped_column(server_default=func.now())
    # The execution (see CellExecution) that produced this run. Someone who
    # pressed Run while that execution was in flight finds the run by it.
    # Null for runs stored before the execution lock existed.
    execution_id: Mapped[uuid.UUID | None] = mapped_column(index=True)


class User(Base):
    __tablename__ = "users"

    id: Mapped[uuid.UUID] = mapped_column(primary_key=True, default=uuid.uuid4)
    # Shown to collaborators next to the user's cursor. From the provider's
    # profile, refreshed at each sign-in.
    name: Mapped[str] = mapped_column(String(200))
    created_at: Mapped[datetime] = mapped_column(server_default=func.now())


class UserIdentity(Base):
    """A sign-in identity (GitHub user 123, Google subject abc) belonging to a user.

    Users are matched by provider and the provider's own user ID, never by
    email, so one provider's unverified email can't take over an account.
    """

    __tablename__ = "user_identities"
    __table_args__ = (
        CheckConstraint(
            "provider IN ('github', 'google', 'dev')", name="ck_user_identities_provider"
        ),
    )

    provider: Mapped[str] = mapped_column(String(20), primary_key=True)
    subject: Mapped[str] = mapped_column(String(255), primary_key=True)
    user_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("users.id", ondelete="CASCADE"), index=True
    )


class AuthSession(Base):
    """A signed-in browser. The cookie holds a random token; this row holds its SHA-256."""

    __tablename__ = "auth_sessions"

    token_hash: Mapped[bytes] = mapped_column(LargeBinary, primary_key=True)
    user_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("users.id", ondelete="CASCADE"), index=True
    )
    created_at: Mapped[datetime] = mapped_column(server_default=func.now())
    expires_at: Mapped[datetime]


class NotebookMember(Base):
    """Who can open a notebook, and with which role."""

    __tablename__ = "notebook_members"
    __table_args__ = (
        CheckConstraint("role IN ('owner', 'editor', 'viewer')", name="ck_notebook_members_role"),
        # Exactly one owner per notebook: the API never makes a second one,
        # and this makes sure no bug can either.
        Index(
            "uq_notebook_members_one_owner",
            "notebook_id",
            unique=True,
            postgresql_where=text("role = 'owner'"),
        ),
    )

    notebook_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("notebooks.id", ondelete="CASCADE"), primary_key=True
    )
    user_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("users.id", ondelete="CASCADE"), primary_key=True, index=True
    )
    role: Mapped[str] = mapped_column(String(16))
    created_at: Mapped[datetime] = mapped_column(server_default=func.now())


class ShareLink(Base):
    """A link that adds whoever opens it (signed in) to a notebook with a role.

    Like sessions, only the SHA-256 of the random token is stored, so the
    table can't be used to mint working links. Revoking deletes the row.
    """

    __tablename__ = "share_links"
    __table_args__ = (
        # Owner is never shareable: a notebook has exactly one owner.
        CheckConstraint("role IN ('editor', 'viewer')", name="ck_share_links_role"),
    )

    id: Mapped[uuid.UUID] = mapped_column(primary_key=True, default=uuid.uuid4)
    notebook_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("notebooks.id", ondelete="CASCADE"), index=True
    )
    token_hash: Mapped[bytes] = mapped_column(LargeBinary, unique=True)
    role: Mapped[str] = mapped_column(String(16))
    created_by: Mapped[uuid.UUID | None] = mapped_column(
        ForeignKey("users.id", ondelete="SET NULL")
    )
    created_at: Mapped[datetime] = mapped_column(server_default=func.now())


class CellExecution(Base):
    """The per-cell execution lock: at most one in-flight run per cell.

    A row exists while a cell's query runs. Pressing Run while it exists
    joins that execution instead of starting another. `expires_at` bounds a
    row left behind by a crashed API process: after it, the lock can be taken.
    """

    __tablename__ = "cell_executions"

    notebook_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("notebooks.id", ondelete="CASCADE"), primary_key=True
    )
    cell_id: Mapped[str] = mapped_column(String(64), primary_key=True)
    execution_id: Mapped[uuid.UUID]
    started_by: Mapped[uuid.UUID | None] = mapped_column(
        ForeignKey("users.id", ondelete="SET NULL")
    )
    started_at: Mapped[datetime]
    expires_at: Mapped[datetime]


class NotebookUpdateLogEntry(Base):
    """One batch of Yjs document updates, appended by the sync server.

    A notebook's document is its snapshot (notebook_snapshots) plus every
    row here for it, applied in any order (Yjs updates commute). The sync
    server is the only writer: it appends a merged batch every fraction of a
    second while people edit, and from time to time compacts the rows into
    the snapshot and deletes exactly the rows it merged, in one transaction.
    """

    __tablename__ = "notebook_updates"
    __table_args__ = (Index("ix_notebook_updates_notebook_id_id", "notebook_id", "id"),)

    # bigserial: a busy notebook appends a row several times a second.
    id: Mapped[int] = mapped_column(BigInteger, primary_key=True)
    notebook_id: Mapped[uuid.UUID] = mapped_column(ForeignKey("notebooks.id", ondelete="CASCADE"))
    update: Mapped[bytes] = mapped_column(LargeBinary)
    created_at: Mapped[datetime] = mapped_column(server_default=func.now())


class AiRequest(Base):
    """One request to the AI assistant, and everything it did: the log of every AI query.

    Kept whatever the outcome, so the assistant's behavior can be audited and
    measured: the prompt, the model, each attempt's SQL, validation error and
    token counts (in `attempts`), the latency and how it ended.
    """

    __tablename__ = "ai_requests"
    __table_args__ = (
        Index("ix_ai_requests_notebook_cell_created", "notebook_id", "cell_id", "created_at"),
        CheckConstraint("kind IN ('generate', 'fix', 'explain')", name="ck_ai_requests_kind"),
        CheckConstraint(
            "status IN ('running', 'succeeded', 'failed')", name="ck_ai_requests_status"
        ),
    )

    id: Mapped[uuid.UUID] = mapped_column(primary_key=True, default=uuid.uuid4)
    notebook_id: Mapped[uuid.UUID] = mapped_column(ForeignKey("notebooks.id", ondelete="CASCADE"))
    cell_id: Mapped[str] = mapped_column(String(64))
    user_id: Mapped[uuid.UUID | None] = mapped_column(ForeignKey("users.id", ondelete="SET NULL"))
    kind: Mapped[str] = mapped_column(String(16))
    # The person's question (generate) or the SQL and error sent (fix/explain).
    prompt: Mapped[dict[str, Any]] = mapped_column(JSON)
    model: Mapped[str] = mapped_column(String(100))
    status: Mapped[str] = mapped_column(String(16))
    # One entry per model call: {"sql", "error", "input_tokens", "output_tokens"}.
    attempts: Mapped[list[dict[str, Any]]] = mapped_column(JSON, default=list)
    input_tokens: Mapped[int] = mapped_column(default=0)
    output_tokens: Mapped[int] = mapped_column(default=0)
    latency_ms: Mapped[int | None]
    error: Mapped[str | None] = mapped_column(Text)
    created_at: Mapped[datetime] = mapped_column(server_default=func.now())
    finished_at: Mapped[datetime | None]


class AiSuggestion(Base):
    """A suggestion the AI made for a cell, waiting for a person to accept or reject it.

    The AI never edits a cell itself: an accepted suggestion is applied by the
    person who accepted it, as their own edit.
    """

    __tablename__ = "ai_suggestions"
    __table_args__ = (
        Index("ix_ai_suggestions_notebook_cell", "notebook_id", "cell_id"),
        CheckConstraint("kind IN ('generate', 'fix', 'explain')", name="ck_ai_suggestions_kind"),
        CheckConstraint(
            "status IN ('pending', 'accepted', 'rejected')", name="ck_ai_suggestions_status"
        ),
    )

    id: Mapped[uuid.UUID] = mapped_column(primary_key=True, default=uuid.uuid4)
    notebook_id: Mapped[uuid.UUID] = mapped_column(ForeignKey("notebooks.id", ondelete="CASCADE"))
    cell_id: Mapped[str] = mapped_column(String(64))
    request_id: Mapped[uuid.UUID] = mapped_column(ForeignKey("ai_requests.id", ondelete="CASCADE"))
    kind: Mapped[str] = mapped_column(String(16))
    status: Mapped[str] = mapped_column(String(16))
    sql: Mapped[str | None] = mapped_column(Text)  # null for explain
    explanation: Mapped[str] = mapped_column(Text)
    # The cell's SQL the request was about (fix/explain); null for generate.
    base_sql: Mapped[str | None] = mapped_column(Text)
    valid: Mapped[bool]
    created_at: Mapped[datetime] = mapped_column(server_default=func.now())
    decided_by: Mapped[uuid.UUID | None] = mapped_column(
        ForeignKey("users.id", ondelete="SET NULL")
    )
    decided_at: Mapped[datetime | None]
