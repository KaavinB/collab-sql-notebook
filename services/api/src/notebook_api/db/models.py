"""SQLAlchemy models. The schema itself changes only through Alembic migrations."""

import uuid
from datetime import datetime
from typing import Any

from sqlalchemy import (
    JSON,
    CheckConstraint,
    DateTime,
    ForeignKey,
    Index,
    LargeBinary,
    String,
    Text,
    func,
)
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column


class Base(DeclarativeBase):
    # Every datetime column is `timestamptz`: stored in UTC, never ambiguous.
    type_annotation_map = {datetime: DateTime(timezone=True)}  # noqa: RUF012


class Notebook(Base):
    __tablename__ = "notebooks"

    id: Mapped[uuid.UUID] = mapped_column(primary_key=True, default=uuid.uuid4)
    title: Mapped[str] = mapped_column(String(200))
    created_at: Mapped[datetime] = mapped_column(server_default=func.now())
    updated_at: Mapped[datetime] = mapped_column(server_default=func.now(), onupdate=func.now())


class NotebookSnapshot(Base):
    """The whole Yjs document as one provisional, single-writer snapshot blob.

    One row per notebook. Phase 2 decides the real snapshot and compaction
    strategy; an update-log table can be added next to this one.
    """

    __tablename__ = "notebook_snapshots"

    notebook_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("notebooks.id", ondelete="CASCADE"), primary_key=True
    )
    state: Mapped[bytes] = mapped_column(LargeBinary)
    updated_at: Mapped[datetime] = mapped_column(server_default=func.now(), onupdate=func.now())


class CellRun(Base):
    """One execution of a cell's SQL and its outcome, shared by everyone.

    Results live here, not in the Yjs document; the document only stores the
    latest run's ID per cell.
    """

    __tablename__ = "cell_runs"
    __table_args__ = (
        Index("ix_cell_runs_notebook_cell_created", "notebook_id", "cell_id", "created_at"),
        CheckConstraint("status IN ('ok', 'error')", name="ck_cell_runs_status"),
        # An ok run has a result and no error; an error run the reverse.
        CheckConstraint(
            "(status = 'ok' AND result IS NOT NULL AND error IS NULL) OR "
            "(status = 'error' AND result IS NULL AND error IS NOT NULL)",
            name="ck_cell_runs_outcome",
        ),
    )

    id: Mapped[uuid.UUID] = mapped_column(primary_key=True, default=uuid.uuid4)
    notebook_id: Mapped[uuid.UUID] = mapped_column(ForeignKey("notebooks.id", ondelete="CASCADE"))
    # Cell IDs are generated by the client and live in the Yjs document.
    cell_id: Mapped[str] = mapped_column(String(64))
    sql: Mapped[str] = mapped_column(Text)
    status: Mapped[str] = mapped_column(String(16))  # "ok" or "error"
    # `json`, not `jsonb`: results are never queried inside, and jsonb rejects
    # the \u0000 escape, which a DuckDB string value can legitimately contain.
    # none_as_null: Python None must be SQL NULL (not JSON 'null'), or the
    # ck_cell_runs_outcome constraint would reject every run.
    result: Mapped[dict[str, Any] | None] = mapped_column(JSON(none_as_null=True))
    error: Mapped[dict[str, Any] | None] = mapped_column(JSON(none_as_null=True))
    created_at: Mapped[datetime] = mapped_column(server_default=func.now())


class User(Base):
    __tablename__ = "users"

    id: Mapped[uuid.UUID] = mapped_column(primary_key=True, default=uuid.uuid4)
    # Shown to collaborators next to the user's cursor. From the provider's
    # profile, refreshed at each sign-in.
    name: Mapped[str] = mapped_column(String(200))
    created_at: Mapped[datetime] = mapped_column(server_default=func.now())


class UserIdentity(Base):
    """A sign-in identity (GitHub user 123, Google subject abc) belonging to a user.

    Users are matched by provider and the provider's own user ID, never by
    email, so one provider's unverified email can't take over an account.
    """

    __tablename__ = "user_identities"
    __table_args__ = (
        CheckConstraint(
            "provider IN ('github', 'google', 'dev')", name="ck_user_identities_provider"
        ),
    )

    provider: Mapped[str] = mapped_column(String(20), primary_key=True)
    subject: Mapped[str] = mapped_column(String(255), primary_key=True)
    user_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("users.id", ondelete="CASCADE"), index=True
    )


class AuthSession(Base):
    """A signed-in browser. The cookie holds a random token; this row holds its SHA-256."""

    __tablename__ = "auth_sessions"

    token_hash: Mapped[bytes] = mapped_column(LargeBinary, primary_key=True)
    user_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("users.id", ondelete="CASCADE"), index=True
    )
    created_at: Mapped[datetime] = mapped_column(server_default=func.now())
    expires_at: Mapped[datetime]


class NotebookMember(Base):
    """Who can open a notebook, and with which role."""

    __tablename__ = "notebook_members"
    __table_args__ = (
        CheckConstraint("role IN ('owner', 'editor', 'viewer')", name="ck_notebook_members_role"),
    )

    notebook_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("notebooks.id", ondelete="CASCADE"), primary_key=True
    )
    user_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("users.id", ondelete="CASCADE"), primary_key=True, index=True
    )
    role: Mapped[str] = mapped_column(String(16))
    created_at: Mapped[datetime] = mapped_column(server_default=func.now())
